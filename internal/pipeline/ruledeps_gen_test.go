//go:build ruledepsgen

package pipeline

// ruledeps_gen.go — writes internal/ruledeps/table.go from the live registry.
//
// WHY A TABLE AT ALL. history.Compute needs, for every producer, the collector steps its claim rests on:
// that is how "the finding is gone" is told apart from "the kind it rests on was not read this time", which
// is the whole point of the comparison gates. HistoryDeps() builds that map from rules.DependenciesByRule
// and analyzers.DependenciesByAnalyzer — and both packages import internal/collect, which imports client-go.
//
// cmd/shoalcheck-mcp must stay cluster-free: depcheck asserts it, and the fence is the reason the MCP server can
// be handed to a model at all. So shoalcheck-mcp passed nil, and a nil map makes EVERY comparison refuse — with a
// sentence blaming the readings for something the caller never supplied.
//
// This is the shape internal/boundaries already uses: a leaf table with a gate in the owning package
// asserting the two agree (TestRuleDeps_TableEqualsTheRegistry). Regenerate with:
//
//	make ruledeps
import (
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/Shoalcheck/shoalcheck-scan/internal/history"
)

// WriteRuleDeps renders the table. Called from TestWriteRuleDeps under the ruledepsgen tag.
func WriteRuleDeps(t *testing.T, path string) {
	t.Helper()
	deps := HistoryDeps()
	ids := make([]string, 0, len(deps))
	for id := range deps {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var b strings.Builder
	b.WriteString(`// Code generated by "make ruledeps"; DO NOT EDIT.

package ruledeps

import "github.com/Shoalcheck/shoalcheck-scan/internal/history"

// table is every producer's dependencies as internal/pipeline builds them from the registry. It exists so a
// binary that must not import client-go can still compare two readings honestly — see the package comment.
var table = map[string]history.Deps{
`)
	for _, id := range ids {
		d := deps[id]
		fmt.Fprintf(&b, "\t%q: {", id)
		if len(d.Kinds) > 0 {
			kinds := append([]string(nil), d.Kinds...)
			sort.Strings(kinds)
			fmt.Fprintf(&b, "Kinds: []string{")
			for i, k := range kinds {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", k)
			}
			b.WriteString("}")
		}
		if d.Usage {
			if len(d.Kinds) > 0 {
				b.WriteString(", ")
			}
			b.WriteString("Usage: true")
		}
		if len(d.Datasets) > 0 {
			if len(d.Kinds) > 0 || d.Usage {
				b.WriteString(", ")
			}
			b.WriteString("Datasets: []history.DatasetDep{")
			ds := append([]history.DatasetDep(nil), d.Datasets...)
			sort.Slice(ds, func(i, j int) bool { return ds[i].Name < ds[j].Name })
			for i, x := range ds {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "{Name: %q, Presence: %v}", x.Name, x.Presence)
			}
			b.WriteString("}")
		}
		if d.Producer != "" {
			if len(d.Kinds) > 0 || d.Usage || len(d.Datasets) > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "Producer: %q", d.Producer)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
	t.Logf("wrote %s — %d producer(s)", path, len(ids))
}

func TestWriteRuleDeps(t *testing.T) {
	WriteRuleDeps(t, "../ruledeps/table.go")
}
